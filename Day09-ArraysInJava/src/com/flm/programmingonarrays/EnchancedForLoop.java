package com.flm.programmingonarrays;

public class EnchancedForLoop {

	public static void main(String[] args) {
		int[] arr= {10,20,30,40};
		//for each loop or EnchancedForLoop
		for(int i:arr) {
			System.out.println(i);
		}
		String[] str= {"pavan", "suresh","ramu"};
		for(String name:str) {
			System.out.println(name);
		}
	}

}
